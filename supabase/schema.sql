-- A safe read-only view for the leaderboard/reveal layer.
-- Picks are not exposed to other players until that individual game's kickoff.
create or replace view public.revealed_picks as
select p.id, p.user_id, p.week_id, p.game_id, p.winner_team, p.confidence, p.spread_team
from public.picks p
join public.games g on g.id=p.game_id
where now() >= g.kickoff;

grant select on public.revealed_picks to authenticated;

